from __future__ import annotations

import os
from datetime import datetime

import pandas as pd
import streamlit as st
from sqlalchemy import create_engine, text

DATABASE_URL = os.getenv("DATABASE_URL", "sqlite:///experiments.db")
engine = create_engine(DATABASE_URL, future=True)

SCENARIOS = [
    "Baseline","Width","Depth","Pooling","Classifier Head","Initialization",
    "Optimizer","Learning Rate","Scheduler","Dropout","Weight Decay",
    "Augmentation","BatchNorm","Deep Plain CNN","Residual Block",
    "ResNet","Ablation","Final Model","Other",
]
MODEL_TYPES = ["BaselineCNN","WideCNN","DeepCNN","ResidualCNN","ResNet","Custom"]
STATUSES = ["planned","running","completed","failed","stopped"]


def init_db() -> None:
    with engine.begin() as conn:
        conn.execute(text("""
            CREATE TABLE IF NOT EXISTS experiments (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                created_at VARCHAR(32) NOT NULL,
                experiment_name VARCHAR(200) NOT NULL UNIQUE,
                scenario VARCHAR(100) NOT NULL,
                model_type VARCHAR(100) NOT NULL,
                status VARCHAR(32) NOT NULL,
                hypothesis TEXT,
                changes_from_baseline TEXT,
                architecture TEXT,
                optimizer VARCHAR(100),
                learning_rate DOUBLE PRECISION,
                batch_size INTEGER,
                epochs INTEGER,
                weight_decay DOUBLE PRECISION,
                momentum DOUBLE PRECISION,
                scheduler VARCHAR(100),
                initialization VARCHAR(100),
                batch_norm BOOLEAN DEFAULT FALSE,
                dropout_enabled BOOLEAN DEFAULT FALSE,
                dropout_rate DOUBLE PRECISION,
                augmentation_enabled BOOLEAN DEFAULT FALSE,
                augmentation TEXT,
                parameter_count BIGINT,
                training_time_seconds DOUBLE PRECISION,
                best_epoch INTEGER,
                train_loss DOUBLE PRECISION,
                val_loss DOUBLE PRECISION,
                test_loss DOUBLE PRECISION,
                train_accuracy DOUBLE PRECISION,
                val_accuracy DOUBLE PRECISION,
                test_accuracy DOUBLE PRECISION,
                precision_macro DOUBLE PRECISION,
                recall_macro DOUBLE PRECISION,
                f1_macro DOUBLE PRECISION,
                checkpoint_path TEXT,
                artifact_path TEXT,
                git_commit VARCHAR(100),
                tags TEXT,
                notes TEXT
            )
        """))


def load_experiments() -> pd.DataFrame:
    return pd.read_sql_query(
        text("SELECT * FROM experiments ORDER BY created_at DESC"),
        engine,
    )


def save_record(record: dict) -> None:
    keys = list(record)
    cols = ", ".join(keys)
    params = ", ".join(f":{k}" for k in keys)
    with engine.begin() as conn:
        conn.execute(
            text(f"INSERT INTO experiments ({cols}) VALUES ({params})"),
            record,
        )


def update_record(experiment_id: int, record: dict) -> None:
    assigns = ", ".join(f"{k}=:{k}" for k in record)
    values = dict(record)
    values["id"] = experiment_id
    with engine.begin() as conn:
        conn.execute(
            text(f"UPDATE experiments SET {assigns} WHERE id=:id"),
            values,
        )


def delete_record(experiment_id: int) -> None:
    with engine.begin() as conn:
        conn.execute(text("DELETE FROM experiments WHERE id=:id"), {"id": experiment_id})


def experiment_form(existing: dict | None = None) -> dict | None:
    existing = existing or {}
    with st.form("experiment_form", clear_on_submit=not existing):
        st.subheader("Experiment identity")
        c1, c2, c3, c4 = st.columns(4)
        name = c1.text_input("Experiment name *", value=existing.get("experiment_name", ""))
        scenario = c2.selectbox(
            "Scenario", SCENARIOS,
            index=SCENARIOS.index(existing.get("scenario", "Baseline"))
            if existing.get("scenario", "Baseline") in SCENARIOS else 0,
        )
        model_type = c3.selectbox(
            "Model type", MODEL_TYPES,
            index=MODEL_TYPES.index(existing.get("model_type", "BaselineCNN"))
            if existing.get("model_type", "BaselineCNN") in MODEL_TYPES else 0,
        )
        status = c4.selectbox(
            "Status", STATUSES,
            index=STATUSES.index(existing.get("status", "planned"))
            if existing.get("status", "planned") in STATUSES else 0,
        )

        hypothesis = st.text_area("Hypothesis / question", value=existing.get("hypothesis") or "")
        changes = st.text_area("Changes from baseline", value=existing.get("changes_from_baseline") or "")
        architecture = st.text_area("Architecture", value=existing.get("architecture") or "")

        st.subheader("Hyperparameters")
        c1, c2, c3, c4 = st.columns(4)
        optimizer = c1.text_input("Optimizer", value=existing.get("optimizer") or "SGD")
        learning_rate = c2.number_input("Learning rate", min_value=0.0, value=float(existing.get("learning_rate") or 0.01), format="%.8f")
        batch_size = c3.number_input("Batch size", min_value=1, value=int(existing.get("batch_size") or 128))
        epochs = c4.number_input("Epochs", min_value=1, value=int(existing.get("epochs") or 20))

        c1, c2, c3, c4 = st.columns(4)
        weight_decay = c1.number_input("Weight decay", min_value=0.0, value=float(existing.get("weight_decay") or 0.0), format="%.8f")
        momentum = c2.number_input("Momentum", min_value=0.0, max_value=1.0, value=float(existing.get("momentum") or 0.0), step=0.01)
        scheduler = c3.text_input("Scheduler", value=existing.get("scheduler") or "")
        initialization = c4.text_input("Initialization", value=existing.get("initialization") or "")

        c1, c2, c3 = st.columns(3)
        batch_norm = c1.checkbox("BatchNorm", value=bool(existing.get("batch_norm", False)))
        dropout_enabled = c2.checkbox("Dropout", value=bool(existing.get("dropout_enabled", False)))
        augmentation_enabled = c3.checkbox("Augmentation", value=bool(existing.get("augmentation_enabled", False)))

        c1, c2 = st.columns(2)
        dropout_rate = c1.number_input("Dropout rate", min_value=0.0, max_value=1.0, value=float(existing.get("dropout_rate") or 0.0), step=0.05, disabled=not dropout_enabled)
        augmentation = c2.text_input("Augmentation details", value=existing.get("augmentation") or "", disabled=not augmentation_enabled)

        st.subheader("Results")
        c1, c2, c3, c4 = st.columns(4)
        parameter_count = c1.number_input("Parameter count", min_value=0, value=int(existing.get("parameter_count") or 0))
        training_time = c2.number_input("Training time (seconds)", min_value=0.0, value=float(existing.get("training_time_seconds") or 0.0))
        best_epoch = c3.number_input("Best epoch", min_value=0, value=int(existing.get("best_epoch") or 0))
        git_commit = c4.text_input("Git commit", value=existing.get("git_commit") or "")

        c1, c2, c3 = st.columns(3)
        train_accuracy = c1.number_input("Train accuracy (%)", 0.0, 100.0, float(existing.get("train_accuracy") or 0.0))
        val_accuracy = c2.number_input("Validation accuracy (%)", 0.0, 100.0, float(existing.get("val_accuracy") or 0.0))
        test_accuracy = c3.number_input("Test accuracy (%)", 0.0, 100.0, float(existing.get("test_accuracy") or 0.0))

        c1, c2, c3 = st.columns(3)
        train_loss = c1.number_input("Train loss", min_value=0.0, value=float(existing.get("train_loss") or 0.0))
        val_loss = c2.number_input("Validation loss", min_value=0.0, value=float(existing.get("val_loss") or 0.0))
        test_loss = c3.number_input("Test loss", min_value=0.0, value=float(existing.get("test_loss") or 0.0))

        c1, c2, c3 = st.columns(3)
        precision_macro = c1.number_input("Macro precision (%)", 0.0, 100.0, float(existing.get("precision_macro") or 0.0))
        recall_macro = c2.number_input("Macro recall (%)", 0.0, 100.0, float(existing.get("recall_macro") or 0.0))
        f1_macro = c3.number_input("Macro F1 (%)", 0.0, 100.0, float(existing.get("f1_macro") or 0.0))

        st.subheader("Artifacts and conclusion")
        c1, c2 = st.columns(2)
        checkpoint_path = c1.text_input("Checkpoint path", value=existing.get("checkpoint_path") or "")
        artifact_path = c2.text_input("Artifact directory", value=existing.get("artifact_path") or "")
        tags = st.text_input("Tags", value=existing.get("tags") or "")
        notes = st.text_area("Observations / conclusion", value=existing.get("notes") or "")

        submitted = st.form_submit_button("Update experiment" if existing else "Save experiment", type="primary")

    if not submitted:
        return None
    if not name.strip():
        st.error("Experiment name is required.")
        return None

    return {
        "created_at": existing.get("created_at") or datetime.now().isoformat(timespec="seconds"),
        "experiment_name": name.strip(),
        "scenario": scenario,
        "model_type": model_type,
        "status": status,
        "hypothesis": hypothesis.strip() or None,
        "changes_from_baseline": changes.strip() or None,
        "architecture": architecture.strip() or None,
        "optimizer": optimizer.strip() or None,
        "learning_rate": float(learning_rate),
        "batch_size": int(batch_size),
        "epochs": int(epochs),
        "weight_decay": float(weight_decay),
        "momentum": float(momentum),
        "scheduler": scheduler.strip() or None,
        "initialization": initialization.strip() or None,
        "batch_norm": bool(batch_norm),
        "dropout_enabled": bool(dropout_enabled),
        "dropout_rate": float(dropout_rate) if dropout_enabled else None,
        "augmentation_enabled": bool(augmentation_enabled),
        "augmentation": augmentation.strip() if augmentation_enabled else None,
        "parameter_count": int(parameter_count) or None,
        "training_time_seconds": float(training_time) or None,
        "best_epoch": int(best_epoch) or None,
        "train_loss": float(train_loss) or None,
        "val_loss": float(val_loss) or None,
        "test_loss": float(test_loss) or None,
        "train_accuracy": float(train_accuracy) or None,
        "val_accuracy": float(val_accuracy) or None,
        "test_accuracy": float(test_accuracy) or None,
        "precision_macro": float(precision_macro) or None,
        "recall_macro": float(recall_macro) or None,
        "f1_macro": float(f1_macro) or None,
        "checkpoint_path": checkpoint_path.strip() or None,
        "artifact_path": artifact_path.strip() or None,
        "git_commit": git_commit.strip() or None,
        "tags": tags.strip() or None,
        "notes": notes.strip() or None,
    }


def main() -> None:
    st.set_page_config(page_title="CIFAR-100 Experiment Lab", page_icon="🧪", layout="wide")
    init_db()
    st.title("CIFAR-100 Experiment Lab")
    st.caption("Controlled experiment tracking for the CNN → ResNet learning project.")

    df = load_experiments()
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Experiments", len(df))
    c2.metric("Completed", int((df["status"] == "completed").sum()) if not df.empty else 0)
    best_val = df["val_accuracy"].max() if not df.empty else None
    best_test = df["test_accuracy"].max() if not df.empty else None
    c3.metric("Best val accuracy", "-" if pd.isna(best_val) else f"{best_val:.2f}%")
    c4.metric("Best test accuracy", "-" if pd.isna(best_test) else f"{best_test:.2f}%")

    dashboard, new, browse, compare, manage = st.tabs(
        ["Dashboard", "New experiment", "Browse", "Compare", "Manage"]
    )

    with dashboard:
        if df.empty:
            st.info("No experiments recorded yet.")
        else:
            st.dataframe(
                df[["experiment_name","scenario","model_type","status","val_accuracy","test_accuracy","parameter_count","created_at"]],
                use_container_width=True,
                hide_index=True,
            )

    with new:
        record = experiment_form()
        if record:
            try:
                save_record(record)
                st.success("Experiment saved.")
                st.rerun()
            except Exception as exc:
                st.error(f"Could not save experiment: {exc}")

    with browse:
        data = load_experiments()
        if data.empty:
            st.info("No experiments recorded yet.")
        else:
            c1, c2, c3 = st.columns(3)
            scenario = c1.selectbox("Scenario filter", ["All"] + sorted(data["scenario"].dropna().unique().tolist()))
            model = c2.selectbox("Model filter", ["All"] + sorted(data["model_type"].dropna().unique().tolist()))
            status = c3.selectbox("Status filter", ["All"] + sorted(data["status"].dropna().unique().tolist()))
            filtered = data.copy()
            if scenario != "All":
                filtered = filtered[filtered["scenario"] == scenario]
            if model != "All":
                filtered = filtered[filtered["model_type"] == model]
            if status != "All":
                filtered = filtered[filtered["status"] == status]
            st.dataframe(filtered, use_container_width=True, hide_index=True)
            st.download_button("Export CSV", filtered.to_csv(index=False).encode("utf-8"), "cifar100_experiments.csv", "text/csv")

    with compare:
        data = load_experiments()
        if len(data) < 2:
            st.info("Record at least two experiments to compare them.")
        else:
            selected = st.multiselect(
                "Experiments to compare",
                data["experiment_name"].tolist(),
                default=data["experiment_name"].tolist()[: min(3, len(data))],
            )
            if selected:
                comp = data[data["experiment_name"].isin(selected)]
                st.dataframe(
                    comp[["experiment_name","scenario","model_type","optimizer","learning_rate","batch_size","epochs","parameter_count","train_accuracy","val_accuracy","test_accuracy","train_loss","val_loss","test_loss"]],
                    use_container_width=True,
                    hide_index=True,
                )
                val = comp[["experiment_name","val_accuracy"]].dropna()
                if not val.empty:
                    st.subheader("Validation accuracy")
                    st.bar_chart(val.set_index("experiment_name"))
                params = comp[["experiment_name","parameter_count"]].dropna()
                if not params.empty:
                    st.subheader("Parameter count")
                    st.bar_chart(params.set_index("experiment_name"))
                for _, row in comp.iterrows():
                    with st.expander(row["experiment_name"]):
                        st.write(f"**Hypothesis:** {row['hypothesis'] or '-'}")
                        st.write(f"**Changes from baseline:** {row['changes_from_baseline'] or '-'}")
                        st.write(f"**Conclusion:** {row['notes'] or '-'}")

    with manage:
        data = load_experiments()
        if data.empty:
            st.info("No experiments recorded yet.")
        else:
            selected_name = st.selectbox("Experiment", data["experiment_name"].tolist())
            row = data[data["experiment_name"] == selected_name].iloc[0].to_dict()
            edit, delete = st.tabs(["Edit", "Delete"])
            with edit:
                record = experiment_form(row)
                if record:
                    try:
                        update_record(int(row["id"]), record)
                        st.success("Experiment updated.")
                        st.rerun()
                    except Exception as exc:
                        st.error(f"Could not update experiment: {exc}")
            with delete:
                st.warning("This deletes only the experiment record, not model artifacts.")
                if st.button("Delete experiment", type="primary"):
                    delete_record(int(row["id"]))
                    st.rerun()


if __name__ == "__main__":
    main()
